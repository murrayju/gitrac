#!/usr/bin/env bun

// ============================================================================
// Build Script - Two-phase build for gitrac
//
// Phase 1: Build the React SPA with Vite (outputs to dist/ui/)
// Phase 2: Generate an entry that embeds every dist/ui file in the binary
//          (`import ... with { type: 'file' }`) and registers them with the
//          server, then compile it into a single binary with
//          `bun build --compile`. The binary needs no files beside it.
//
// Usage:
//   ./bun run scripts/build.ts
//   ./bun run scripts/build.ts --outfile=./bin/gitrac --minify --sourcemap
//   ./bun run scripts/build.ts --target=bun-linux-x64 --outfile=gitrac-linux-x64
// ============================================================================

import { readdir } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { parseArgs } from 'node:util';

const ROOT = resolve(import.meta.dir, '..');
const UI_DIR = join(ROOT, 'dist', 'ui');
const ENTRY = join(ROOT, 'dist', 'gitrac-entry.ts');

const { values } = parseArgs({
  options: {
    outfile: { type: 'string', default: './bin/gitrac' },
    target: { type: 'string' },
    minify: { type: 'boolean', default: false },
    sourcemap: { type: 'boolean', default: false },
    'skip-ui': { type: 'boolean', default: false },
  },
  strict: false,
  allowPositionals: true,
});

// Phase 1: Build the React SPA with Vite
if (!values['skip-ui']) {
  console.log('Phase 1: Building UI with Vite...');
  const vite = Bun.spawn(
    ['./bun', 'run', 'vite', 'build', '--config', 'vite.config.ts'],
    {
      stdio: ['inherit', 'inherit', 'inherit'],
    },
  );
  const viteExitCode = await vite.exited;
  if (viteExitCode !== 0) {
    console.error('Vite build failed');
    process.exit(viteExitCode);
  }
  console.log('UI build complete.\n');
}

// Phase 2: Compile the CLI binary with the UI embedded
console.log('Phase 2: Compiling binary...');
if (!(await Bun.file(join(UI_DIR, 'index.html')).exists())) {
  console.error(`No built UI at ${UI_DIR} (run without --skip-ui)`);
  process.exit(1);
}
await Bun.write(ENTRY, await embeddedEntrySource());

const args = ['build', ENTRY, '--compile', `--outfile=${values.outfile}`];

if (values.minify) args.push('--minify');
if (values.sourcemap) args.push('--sourcemap');
if (values.target) args.push(`--target=${values.target}`);

const proc = Bun.spawn(['./bun', ...args], {
  stdio: ['inherit', 'inherit', 'inherit'],
});
const exitCode = await proc.exited;

if (exitCode === 0) {
  console.log(`\nBinary built: ${values.outfile}`);
}

process.exit(exitCode);

/** Relative import specifier from the generated entry to `file`. */
function specifier(file: string): string {
  const rel = relative(dirname(ENTRY), file).split(sep).join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

/** Source of the compile entry: embed dist/ui, register it, run the CLI. */
async function embeddedEntrySource(): Promise<string> {
  const files = (
    await readdir(UI_DIR, { recursive: true, withFileTypes: true })
  )
    .filter((e) => e.isFile())
    .map((e) => join(e.parentPath, e.name))
    .sort();
  const imports: string[] = [];
  const entries: string[] = [];
  files.forEach((file, i) => {
    const urlPath = `/${relative(UI_DIR, file).split(sep).join('/')}`;
    imports.push(
      `import f${i} from ${JSON.stringify(specifier(file))} with { type: 'file' };`,
    );
    entries.push(`  ${JSON.stringify(urlPath)}: f${i},`);
  });
  console.log(`Embedding ${files.length} UI files from ${UI_DIR}`);
  return [
    '// Generated by scripts/build.ts — do not edit.',
    `import { runCli } from ${JSON.stringify(specifier(join(ROOT, 'src', 'cli', 'index.ts')))};`,
    `import { registerEmbeddedUi } from ${JSON.stringify(specifier(join(ROOT, 'src', 'web', 'ui-assets.ts')))};`,
    ...imports,
    '',
    'registerEmbeddedUi({',
    ...entries,
    '});',
    '',
    'await runCli();',
    '',
  ].join('\n');
}
